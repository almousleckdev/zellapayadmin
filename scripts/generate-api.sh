#!/usr/bin/env bash
# Regenerates the typed API description from the backend contract.
set -euo pipefail

spec="../zellapay/api/admin.openapi.yaml"
out="lib/api/generated/admin.ts"

[ -f "$spec" ] || { echo "missing $spec: is ../zellapay checked out?" >&2; exit 1; }
tmp="$(mktemp)"
pnpm exec openapi-typescript "$spec" -o "$tmp" >/dev/null
{ echo "// Code generated by scripts/generate-api.sh from $spec. DO NOT EDIT."; cat "$tmp"; } > "$out"
rm -f "$tmp"
echo "wrote $out"
